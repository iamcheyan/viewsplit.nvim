local root = vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":h:h")
vim.opt.runtimepath:prepend(root)
local viewsplit = require("viewsplit")
viewsplit.setup({ search = false, selection = false, folds = false, jumps = true })

local buf = vim.api.nvim_create_buf(true, false)
vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "a", "b", "c", "d", "e" })
local a = vim.api.nvim_get_current_win()
vim.api.nvim_win_set_buf(a, buf)
vim.cmd("vsplit")
local b = vim.api.nvim_get_current_win()
vim.api.nvim_win_set_buf(b, buf)

local function move(win, row)
  vim.api.nvim_set_current_win(win)
  vim.api.nvim_win_set_cursor(win, { row, 0 })
  vim.api.nvim_exec_autocmds("CursorMoved", { buffer = buf })
end

move(a, 2)
move(a, 4)
local sa = viewsplit.view(a)
assert(#sa.jumplist >= 2 and sa.jump_cursor.lnum == 4, "A collects its cursor history")
move(b, 1)
move(b, 3)
local sb = viewsplit.view(b)
assert(#sb.jumplist >= 2 and sb.jump_cursor.lnum == 3, "B collects its cursor history")
assert(sa.jump_cursor.lnum == 4, "B movement must not modify A history")
assert(viewsplit.jump_back(b), "B should move backward")
assert(vim.api.nvim_win_get_cursor(b)[1] == 1, "B back target should be its own prior position")
assert(vim.fn.maparg("<C-o>", "n") == "", "ViewSplit leaves native jump-back mapping untouched")
assert(vim.fn.maparg("<C-i>", "n") == "", "ViewSplit leaves native jump-forward mapping untouched")

print("jumps_spec: OK")
