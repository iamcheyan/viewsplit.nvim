local root = vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":h:h")
vim.opt.runtimepath:prepend(root)
local View = require("viewsplit.view")
local Scroll = require("viewsplit.scroll")
local api = vim.api

local buf = api.nvim_create_buf(true, false)
api.nvim_buf_set_lines(buf, 0, -1, false, vim.tbl_map(function(i) return "line " .. i end, vim.fn.range(1, 80)))
local a = api.nvim_get_current_win()
api.nvim_win_set_buf(a, buf)
api.nvim_win_set_height(a, 10)
vim.cmd("vsplit")
local b = api.nvim_get_current_win()
api.nvim_win_set_buf(b, buf)
api.nvim_win_set_height(b, 10)

api.nvim_set_current_win(a)
api.nvim_win_set_cursor(a, { 48, 3 })
vim.cmd("normal! zt")
local sa = View.new(a)
View.capture(sa)
assert(sa.cursor[1] == 48, "view A cursor should be captured")
assert(sa.topline > 1, "view A topline should be captured")

api.nvim_set_current_win(b)
api.nvim_win_set_cursor(b, { 12, 0 })
vim.cmd("normal! zt")
local sb = View.new(b)
View.capture(sb)
assert(sb.topline ~= sa.topline, "split viewports should have different top lines")

api.nvim_set_current_win(a)
api.nvim_win_set_cursor(a, { 1, 0 })
View.restore(sa)
assert(api.nvim_win_get_cursor(a)[1] == 48, "view A cursor should restore")
assert(vim.fn.line("w0") == sa.topline, "view A top line should restore")

api.nvim_set_current_win(b)
api.nvim_win_set_cursor(b, { 80, 0 })
View.restore(sb)
assert(api.nvim_win_get_cursor(b)[1] == 12, "view B cursor should restore")
assert(vim.fn.line("w0") == sb.topline, "view B top line should restore")

print("scroll_spec: OK")
